#case conversion string methods
#capitalize() - first letter of string
'''s1 = 'python is easy'
s2 = s1.capitalize()
print(s2)'''

#upper()
'''s1 = 'hello world'
s2 = s1.upper()
print(s2)'''

#lower()
s1 = 'HELLO world'
s2 = s1.lower()
print(s2)

#title() - every word in string first letter capital
s1 = 'python is easy'
s2 = s1.title()
print(s2)

#swapcase()-lower become upper &viseversa
s1 = 'Python Is Easy'
s2 = s1.swapcase()
print(s2)

#casefold()- same as lower but this works for all languages
s1 = 'HELLO world'
s2 = s1.casefold()
print(s2)